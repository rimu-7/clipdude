//! OS integration: clipboard change detection, the frontmost app, and simulated paste.

pub use imp::*;

#[cfg(target_os = "macos")]
mod imp {
    use core_foundation::base::TCFType;
    use core_foundation::boolean::CFBoolean;
    use core_foundation::dictionary::{CFDictionary, CFDictionaryRef};
    use core_foundation::string::{CFString, CFStringRef};
    use core_graphics::event::{CGEvent, CGEventFlags, CGEventTapLocation};
    use core_graphics::event_source::{CGEventSource, CGEventSourceStateID};
    use objc2::rc::autoreleasepool;
    use objc2_app_kit::{NSPasteboard, NSWorkspace};

    /// Pasteboard types that password managers use to mark content as private or temporary
    /// (see nspasteboard.org).
    const PRIVATE_TYPES: [&str; 4] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ];
    const KEY_V: u16 = 9;

    #[link(name = "ApplicationServices", kind = "framework")]
    extern "C" {
        fn AXIsProcessTrusted() -> bool;
        fn AXIsProcessTrustedWithOptions(options: CFDictionaryRef) -> bool;
        static kAXTrustedCheckOptionPrompt: CFStringRef;
    }

    /// A counter that changes whenever anything is copied; cheap to poll.
    pub fn change_token() -> Option<i64> {
        autoreleasepool(|_| Some(NSPasteboard::generalPasteboard().changeCount() as i64))
    }

    pub fn clipboard_is_private() -> bool {
        autoreleasepool(|_| {
            let Some(types) = NSPasteboard::generalPasteboard().types() else {
                return false;
            };
            types
                .iter()
                .any(|kind| PRIVATE_TYPES.contains(&kind.to_string().as_str()))
        })
    }

    pub fn frontmost_app() -> String {
        autoreleasepool(|_| {
            NSWorkspace::sharedWorkspace()
                .frontmostApplication()
                .and_then(|app| app.bundleIdentifier().or_else(|| app.localizedName()))
                .map(|name| name.to_string())
                .unwrap_or_default()
        })
    }

    pub fn remember_foreground() {}

    pub fn restore_foreground() {}

    /// Posting keystrokes needs Accessibility access. Shows the system prompt when missing.
    pub fn ensure_paste_permission() -> Result<(), String> {
        if unsafe { AXIsProcessTrusted() } {
            return Ok(());
        }
        unsafe {
            let key = CFString::wrap_under_get_rule(kAXTrustedCheckOptionPrompt);
            let options = CFDictionary::from_CFType_pairs(&[(key, CFBoolean::true_value())]);
            AXIsProcessTrustedWithOptions(options.as_concrete_TypeRef());
        }
        Err("Copied. To paste automatically, allow ClipDude in System Settings → Privacy & Security → Accessibility.".into())
    }

    pub fn send_paste() -> Result<(), String> {
        let source = CGEventSource::new(CGEventSourceStateID::HIDSystemState)
            .map_err(|_| "Could not create a keyboard event source.".to_string())?;
        for key_down in [true, false] {
            let event = CGEvent::new_keyboard_event(source.clone(), KEY_V, key_down)
                .map_err(|_| "Could not create the paste keystroke.".to_string())?;
            event.set_flags(CGEventFlags::CGEventFlagCommand);
            event.post(CGEventTapLocation::HID);
        }
        Ok(())
    }
}

#[cfg(windows)]
mod imp {
    use std::sync::atomic::{AtomicIsize, Ordering};

    use windows_sys::Win32::Foundation::{CloseHandle, HWND};
    use windows_sys::Win32::System::DataExchange::{
        GetClipboardSequenceNumber, IsClipboardFormatAvailable, RegisterClipboardFormatW,
    };
    use windows_sys::Win32::System::Threading::{
        GetCurrentProcessId, OpenProcess, QueryFullProcessImageNameW,
        PROCESS_QUERY_LIMITED_INFORMATION,
    };
    use windows_sys::Win32::UI::Input::KeyboardAndMouse::{
        SendInput, INPUT, INPUT_0, INPUT_KEYBOARD, KEYBDINPUT, KEYEVENTF_KEYUP, VK_CONTROL,
    };
    use windows_sys::Win32::UI::WindowsAndMessaging::{
        GetForegroundWindow, GetWindowThreadProcessId, IsWindow, SetForegroundWindow,
    };

    const VK_V: u16 = 0x56;
    /// Formats that password managers set to keep content out of clipboard history.
    const PRIVATE_FORMATS: [&str; 2] = [
        "ExcludeClipboardContentFromMonitorProcessing",
        "Clipboard Viewer Ignore",
    ];

    static PREVIOUS_WINDOW: AtomicIsize = AtomicIsize::new(0);

    fn wide(text: &str) -> Vec<u16> {
        text.encode_utf16().chain(std::iter::once(0)).collect()
    }

    fn window_pid(hwnd: HWND) -> u32 {
        let mut pid = 0u32;
        unsafe { GetWindowThreadProcessId(hwnd, &mut pid) };
        pid
    }

    pub fn change_token() -> Option<i64> {
        Some(i64::from(unsafe { GetClipboardSequenceNumber() }))
    }

    pub fn clipboard_is_private() -> bool {
        PRIVATE_FORMATS.iter().any(|name| unsafe {
            let format = RegisterClipboardFormatW(wide(name).as_ptr());
            format != 0 && IsClipboardFormatAvailable(format) != 0
        })
    }

    pub fn frontmost_app() -> String {
        let hwnd = unsafe { GetForegroundWindow() };
        if hwnd.is_null() {
            return String::new();
        }
        let pid = window_pid(hwnd);
        if pid == 0 {
            return String::new();
        }
        unsafe {
            let process = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, pid);
            if process.is_null() {
                return String::new();
            }
            let mut buffer = [0u16; 1024];
            let mut len = buffer.len() as u32;
            let ok = QueryFullProcessImageNameW(process, 0, buffer.as_mut_ptr(), &mut len);
            CloseHandle(process);
            if ok == 0 {
                return String::new();
            }
            let path = String::from_utf16_lossy(&buffer[..len as usize]);
            path.rsplit(['\\', '/']).next().unwrap_or_default().to_string()
        }
    }

    /// Remembers the window the user was in so smart paste can return to it.
    pub fn remember_foreground() {
        let hwnd = unsafe { GetForegroundWindow() };
        if !hwnd.is_null() && window_pid(hwnd) != unsafe { GetCurrentProcessId() } {
            PREVIOUS_WINDOW.store(hwnd as isize, Ordering::Relaxed);
        }
    }

    pub fn restore_foreground() {
        let hwnd = PREVIOUS_WINDOW.load(Ordering::Relaxed) as HWND;
        if !hwnd.is_null() && unsafe { IsWindow(hwnd) } != 0 {
            unsafe { SetForegroundWindow(hwnd) };
        }
    }

    pub fn ensure_paste_permission() -> Result<(), String> {
        Ok(())
    }

    fn key(vk: u16, up: bool) -> INPUT {
        INPUT {
            r#type: INPUT_KEYBOARD,
            Anonymous: INPUT_0 {
                ki: KEYBDINPUT {
                    wVk: vk,
                    wScan: 0,
                    dwFlags: if up { KEYEVENTF_KEYUP } else { 0 },
                    time: 0,
                    dwExtraInfo: 0,
                },
            },
        }
    }

    pub fn send_paste() -> Result<(), String> {
        let inputs = [
            key(VK_CONTROL, false),
            key(VK_V, false),
            key(VK_V, true),
            key(VK_CONTROL, true),
        ];
        let sent = unsafe {
            SendInput(
                inputs.len() as u32,
                inputs.as_ptr(),
                std::mem::size_of::<INPUT>() as i32,
            )
        };
        if sent as usize == inputs.len() {
            Ok(())
        } else {
            Err("Copied, but Windows blocked the paste keystroke. Press Ctrl+V to paste.".into())
        }
    }
}

#[cfg(target_os = "linux")]
mod imp {
    use std::path::Path;
    use std::process::{Command, Stdio};
    use std::sync::OnceLock;

    #[derive(Clone, Copy)]
    enum PasteTool {
        Xdotool,
        Wtype,
        Ydotool,
    }

    fn on_path(program: &str) -> bool {
        std::env::var_os("PATH")
            .map(|paths| std::env::split_paths(&paths).any(|dir| dir.join(program).is_file()))
            .unwrap_or(false)
    }

    fn is_wayland() -> bool {
        std::env::var_os("WAYLAND_DISPLAY").is_some()
    }

    fn has_xdotool() -> bool {
        static FOUND: OnceLock<bool> = OnceLock::new();
        *FOUND.get_or_init(|| on_path("xdotool"))
    }

    fn paste_tool() -> Option<PasteTool> {
        static TOOL: OnceLock<Option<PasteTool>> = OnceLock::new();
        *TOOL.get_or_init(|| {
            let candidates: &[(&str, PasteTool)] = if is_wayland() {
                &[
                    ("wtype", PasteTool::Wtype),
                    ("ydotool", PasteTool::Ydotool),
                    ("xdotool", PasteTool::Xdotool),
                ]
            } else {
                &[("xdotool", PasteTool::Xdotool)]
            };
            candidates
                .iter()
                .find(|(program, _)| on_path(program))
                .map(|(_, tool)| *tool)
        })
    }

    /// X11 offers no cheap change counter, so the monitor compares contents instead.
    pub fn change_token() -> Option<i64> {
        None
    }

    pub fn clipboard_is_private() -> bool {
        false
    }

    pub fn frontmost_app() -> String {
        if is_wayland() || !has_xdotool() {
            return String::new();
        }
        let output = Command::new("xdotool")
            .args(["getactivewindow", "getwindowpid"])
            .stderr(Stdio::null())
            .output();
        let Ok(output) = output else {
            return String::new();
        };
        let pid = String::from_utf8_lossy(&output.stdout).trim().to_string();
        if pid.is_empty() || !pid.chars().all(|c| c.is_ascii_digit()) {
            return String::new();
        }
        std::fs::read_to_string(Path::new("/proc").join(pid).join("comm"))
            .map(|name| name.trim().to_string())
            .unwrap_or_default()
    }

    pub fn remember_foreground() {}

    pub fn restore_foreground() {}

    pub fn ensure_paste_permission() -> Result<(), String> {
        paste_tool().map(|_| ()).ok_or_else(|| {
            "Copied. To paste automatically, install xdotool (X11) or wtype (Wayland).".to_string()
        })
    }

    pub fn send_paste() -> Result<(), String> {
        let (program, args): (&str, &[&str]) = match paste_tool() {
            Some(PasteTool::Xdotool) => ("xdotool", &["key", "--clearmodifiers", "ctrl+v"]),
            Some(PasteTool::Wtype) => ("wtype", &["-M", "ctrl", "v", "-m", "ctrl"]),
            Some(PasteTool::Ydotool) => ("ydotool", &["key", "29:1", "47:1", "47:0", "29:0"]),
            None => return ensure_paste_permission(),
        };
        let status = Command::new(program)
            .args(args)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .map_err(|e| format!("Copied, but {program} failed: {e}"))?;
        if status.success() {
            Ok(())
        } else {
            Err(format!("Copied, but {program} could not paste. Press Ctrl+V to paste."))
        }
    }
}
